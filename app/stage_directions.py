"""Ремарки в звёздочках: `*кивает*`, `*пауза*`, `*внимательный взгляд*`.

Модель начинает отыгрывать роль как в сценарии пьесы и вставляет действия
между репликами. Замерено на живой сессии: **11 реплик из 17** содержали такую
ремарку, а одна и вовсе пересказывала вслух инструкцию из подсказки этапа
(«Собеседник не закончил фразу. Дайте ему момент подумать»).

Это не эмоция и не разметка — у эмоций свой канал (`[emo:...]`), у него белый
список и связь с лицом аватара. Звёздочка же уходит в синтез и звучит буквально:
«звёздочка кивок звёздочка». То же самое, что было с управляющим JSON, когда
агент произносил «фигурная скобка action next stage».

Чиним там же, где остальную разметку — в `speakable`, а не только перед
синтезом: иначе ремарка пропадёт из озвучки и останется в истории на экране, в
расшифровке отчёта и в контексте следующего запроса.

Просить модель в промпте недостаточно: она уже просилась не выводить ничего,
кроме тегов, и всё равно выводила. Промпт — вежливость, парсер — гарантия.
"""
from __future__ import annotations

import re

# `*кивает*`, `*короткая пауза*`. Внутри — без переводов строки и без вложенных
# звёздочек; длину ограничиваем, чтобы случайная одиночная звёздочка в начале
# реплики не съела половину текста до следующей.
_PAIRED = re.compile(r"\*[^*\n]{1,120}\*")

# Звёздочка, оставшаяся без пары. Одиночная в тексте не значит ничего, а
# озвучивается как «звёздочка», поэтому убираем и её.
_LONE = re.compile(r"\*+")

# Строка целиком из ремарки: `(кивает)` или `— пауза —` тоже встречаются, но
# круглые скобки бывают и в осмысленной речи («сто (сто двадцать) тысяч»),
# поэтому трогаем только те, что занимают ВСЮ строку.
_WHOLE_LINE = re.compile(r"^\s*[(（][^)）\n]{1,120}[)）]\s*$", re.M)


def strip(text: str) -> str:
    """Убрать ремарки. Возвращает то, что можно произнести вслух."""
    if not text:
        return ""
    out = _PAIRED.sub(" ", text)
    out = _WHOLE_LINE.sub("", out)
    out = _LONE.sub("", out)
    # После вырезания остаются двойные пробелы и осиротевшая пунктуация в
    # начале строки — синтез прочитает их как заминку.
    out = re.sub(r"[ \t]{2,}", " ", out)
    out = re.sub(r"\n{3,}", "\n\n", out)
    out = re.sub(r"^[ \t]*[,;:—-]+[ \t]*", "", out, flags=re.M)
    return out.strip()


def count(text: str) -> int:
    """Сколько ремарок было. Нужно, чтобы мерить, а не гадать."""
    if not text:
        return 0
    return len(_PAIRED.findall(text)) + len(_WHOLE_LINE.findall(text))


SYSTEM_HINT = """
Ты говоришь вслух, тебя слышат. Не описывай свои действия и не ставь ремарки:
никаких «*кивает*», «*пауза*», «*задумчиво смотрит*» — ни в звёздочках, ни в
скобках. Если нужна пауза, просто поставь точку.

Не пересказывай вслух инструкции, которые получил: собеседник их не слышал и не
должен слышать.
""".strip()
