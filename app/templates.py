def template(kind: str, title: str = "", source_text: str = "") -> dict:
    """Скелет сценария по типу тренировки. Всегда валиден."""
    fam = _FAMILY.get(kind, "interview")
    role, tone, strict, pressure, emo = _PERSONA[fam]
    return {
        "title": title or f"Тренировка: {TYPES.get(kind, TYPES['generic'])}",
        "type": kind if kind in TYPES else "generic",
        "persona": {"role": role, "tone": tone, "strictness": strict,
                    "pressure": pressure, "start_emotion": emo},
        "stages": [{"goal": goal, "hint": hint, "advance_when": adv,
                    "opening": "", "max_turns": budget}
                   for goal, hint, adv, budget in _SKELETONS[fam]],
        "criteria": [{"title": t, "anchor_1": a1, "anchor_5": a5}
                     for t, a1, a5 in CRITERIA],
        "source_text": source_text,
    }
