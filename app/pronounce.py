def _spell_out(word: str) -> str:
    """Аббревиатура по буквам, СЛИТНО.

    Дефисы напрашиваются, но измерено обратное: на всех пяти проверенных
    аббревиатурах слитная форма выравнивается лучше дефисной, а «эйч-ар»
    выровнялся в пустоту вовсе — таймкодов ноль, рот на этом слове не
    двигается. Слитное «эйчар» дало сходство 0.97 против 0.90.
    """
    return "".join(_LETTERS.get(c, c) for c in word.lower())


def _transliterate(word: str) -> str:
    low = word.lower()
    out, i = [], 0
    while i < len(low):
        for size in (3, 2, 1):
            piece = low[i:i + size]
            if piece in _TRANSLIT:
                out.append(_TRANSLIT[piece])
                i += size
                break
        else:
            i += 1
    return "".join(out)


def latin_word(word: str) -> str:
    """Латинское слово -> кириллица.

    Три правила по убыванию надёжности: словарь, чтение по буквам для
    аббревиатур, транслитерация для остального. Аббревиатуру определяем по
    верхнему регистру — «SLA» читается по буквам, «Slack» нет.
    """
    low = word.lower()
    if low in TERMS:
        return TERMS[low]
    # Одиночная буква — всегда имя буквы: «p95» это «пи девяносто пять», а не
    # «п девяносто пять». Транслитерация тут даёт полузвук вместо слова.
    if len(word) == 1:
        return _LETTERS.get(low, low)
    if word.isupper() and len(word) <= 5:
        return _spell_out(word)
    return _transliterate(word)


# ------------------------------------------------------------------- разбор

# Смешанные жетоны вроде «p95» или «5xx» разбираем по частям.
_TOKEN = re.compile(r"[A-Za-z]+|\d+")
_MIXED = re.compile(r"[A-Za-z0-9]*[A-Za-z][A-Za-z0-9]*|\d+(?:[.,]\d+)?")

# Знаки, которые модель тоже выбрасывает. Число перед знаком нужно, чтобы
# согласовать форму: «пятнадцать процентов», но «один процент».
_SIGNS = re.compile(r"(\d+(?:[.,]\d+)?)\s*([%\u2116\u00b0])|([%\u2116\u00b0])")
_SIGN_FORMS = {
    "%": ("процент", "процента", "процентов"),
    "\u2116": ("номер", "номер", "номер"),
    "\u00b0": ("градус", "градуса", "градусов"),
}


def _decimal(whole: str, frac: str) -> str:
    """«99.9» -> «девяносто девять и девять».

    Строгое «целых / десятых» звучит как школьная доска. В речи говорят «и».
    """
    return f"{number_words(int(whole))} и {number_words(int(frac))}"


def _token(tok: str) -> str:
    m = re.fullmatch(r"(\d+)[.,](\d+)", tok)
    if m:
        return _decimal(m.group(1), m.group(2))
    if tok.isdigit():
        return number_words(int(tok))
    if tok.isalpha():
        return latin_word(tok)
    # Смесь букв и цифр: «p95», «k8s», «5xx». Словарь смотрим целиком (там
    # есть «k8s»), иначе разбираем по кускам.
    if tok.lower() in TERMS:
        return TERMS[tok.lower()]
    return " ".join(_token(part) for part in _TOKEN.findall(tok))


def normalize(text: str) -> str:
    """Текст, готовый к синтезу русской моделью.

    Кириллица и пунктуация не трогаются. Заменяется только то, что модель
    иначе выбросит: латиница и цифры.
    """
    if not text:
        return text
    text = _SIGNS.sub(_sign, text)
    return _MIXED.sub(lambda m: _token(m.group(0)), text)


def _sign(m: re.Match) -> str:
    num, sign, lone = m.group(1), m.group(2), m.group(3)
    if lone:
        return " " + _SIGN_FORMS[lone][2]
    # Дробное всегда во множественном: «девять и пять процентов».
    whole = int(re.split(r"[.,]", num)[0])
    form = _SIGN_FORMS[sign][2] if "." in num or "," in num \
        else _plural(whole, _SIGN_FORMS[sign])
    return f"{num} {form}"


def word_map(text: str) -> list[int]:
    """Сколько произносимых слов даёт каждое слово исходного текста.

    Нужна субтитрам. Они раздают таймкоды, сопоставляя i-е слово оригинала с
    i-м словом расшифровки, а нормализация это соответствие рвёт: «p95» — одно
    слово, «пи девяносто пять» — три, и всё, что стоит дальше по клаузе,
    получает чужое время и выскакивает раньше звука.

    Считаем по словам, а не пропорционально: тут возможен точный ответ, и
    брать приблизительный незачем.
    """
    return [len(normalize(w).split()) or 1 for w in text.split()]
