"""Нормализация текста перед синтезом: латиница и числа.

Русская модель Silero молча выбрасывает всё, чего нет в её алфавите. Не
заменяет, не читает по буквам — стирает. Проверено на `v5_cis_base/ru_roman`:

    «Расскажите про ваш backend и REST API.»  ->  «расскажите про ваш и»
    «SLA у нас 99.9 процента.»                ->  «у нас процента»

Для тренажёра собеседований это не косметика: реплики агента состоят из
терминов и цифр, и без нормализации он произносит бессмыслицу, а в субтитрах
при этом стоит осмысленный текст. Расхождение звука и субтитров человек
замечает мгновенно.

Нормализуется ТОЛЬКО то, что уходит в синтез. Субтитры, история и отчёт
показывают исходный текст: «p95» читается глазами лучше, чем «пэ девяносто
пять».
"""
from __future__ import annotations

import re

# --------------------------------------------------------------- числительные

_ONES_M = ["", "один", "два", "три", "четыре", "пять", "шесть", "семь",
           "восемь", "девять"]
_ONES_F = ["", "одна", "две", "три", "четыре", "пять", "шесть", "семь",
           "восемь", "девять"]
_TEENS = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
          "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать",
          "девятнадцать"]
_TENS = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят",
         "семьдесят", "восемьдесят", "девяносто"]
_HUNDREDS = ["", "сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот",
             "семьсот", "восемьсот", "девятьсот"]


def _plural(n: int, forms: tuple[str, str, str]) -> str:
    """Русское согласование: 1 тысяча, 2 тысячи, 5 тысяч."""
    n = abs(n) % 100
    if 11 <= n <= 19:
        return forms[2]
    n %= 10
    if n == 1:
        return forms[0]
    if 2 <= n <= 4:
        return forms[1]
    return forms[2]


def _under_thousand(n: int, feminine: bool = False) -> list[str]:
    out = []
    if n >= 100:
        out.append(_HUNDREDS[n // 100])
        n %= 100
    if 10 <= n <= 19:
        out.append(_TEENS[n - 10])
        return out
    if n >= 20:
        out.append(_TENS[n // 10])
        n %= 10
    if n:
        out.append((_ONES_F if feminine else _ONES_M)[n])
    return out


def number_words(n: int) -> str:
    """Целое число словами, именительный падеж.

    Падежи не склоняются намеренно. Согласовать «двух тысяч запросов» без
    разбора предложения нельзя, а именительный падеж звучит как лёгкая
    неловкость — в отличие от тишины, которая звучит как поломка.
    """
    if n == 0:
        return "ноль"
    if n < 0:
        return "минус " + number_words(-n)
    parts = []
    if n >= 1_000_000_000:
        b, n = divmod(n, 1_000_000_000)
        parts += _under_thousand(b) + [_plural(b, ("миллиард", "миллиарда", "миллиардов"))]
    if n >= 1_000_000:
        m, n = divmod(n, 1_000_000)
        parts += _under_thousand(m) + [_plural(m, ("миллион", "миллиона", "миллионов"))]
    if n >= 1000:
        t, n = divmod(n, 1000)
        # Тысяча женского рода: «две тысячи», не «два тысячи».
        parts += _under_thousand(t, feminine=True) + [_plural(t, ("тысяча", "тысячи", "тысяч"))]
    parts += _under_thousand(n)
    return " ".join(p for p in parts if p)


